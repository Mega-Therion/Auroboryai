#!/usr/bin/env python3
"""Build Typst PDFs that preserve the repository's canonical paper PDFs page-for-page.

The source papers are maintained as LaTeX and already contain the complete academic
text, equations, abstracts, and bibliographies. This script rasterizes each canonical
PDF at print-quality resolution and places those pages in a Typst document, producing
portable Typst-owned PDFs without lossy macro conversion.
"""
from pathlib import Path
import subprocess
import re

ROOT = Path(__file__).resolve().parents[1]
PAPERS = [
    ("res-nova", "res-nova", "Res Nova"),
    ("euclid-predictions", "shadow-ladder-euclid-dr1-predictions-paper", "The Shadow Ladder: pinch-point predictions for Euclid DR1"),
    ("A", "law-of-god-successor", "The Law of GOD: A Pleroma of Geometrically Ordered Dynamics"),
    ("B", "IT-PLEROMA-god-distilled", "Information Tension as Primitive, the RYTT Codec as Conjectural Semiotics"),
    ("C", "flagship", "Information Tension as a Unifying Action Principle"),
    ("D", "geometric-phase-force", "The Geometric Phase Force"),
    ("E", "geometric-foundation", "A Geometric Foundation for Information Tension"),
    ("F", "adccl-successor", "The Anti-Drift Cognitive Control Loop"),
    ("G", "omega-successor", "T.O.A. — The OmegA Architecture"),
    ("H", "neurotopo-successor", "Neuro-Topological Stability"),
    ("I", "holonomery", "Holonomery"),
    ("J", "abc-successor", "The Articulated Binary Chirallic System"),
    ("K", "conformal-successor", "Conformal Parameterization of the Sovereign Constants"),
    ("L", "resourceholonomy-successor", "Resource Holonomy"),
    ("M", "omegacdm", "OmegaCDM: A Pre-Registered Cosmological Prediction"),
]


def run(*args):
    subprocess.run(args, cwd=ROOT, check=True)


def latex_title(tex: Path, fallback: str) -> str:
    text = tex.read_text(errors="ignore")
    m = re.search(r"\\title\{([^{}]+)\}", text)
    return (m.group(1) if m else fallback).replace("\\", "")


def typst_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def build_one(dirname: str, stem: str, fallback: str):
    d = ROOT / "papers" / dirname
    source_pdf = d / f"{stem}.pdf"
    source_tex = d / f"{stem}.tex"
    out = d / "typst"
    pages = out / "pages"
    pages.mkdir(parents=True, exist_ok=True)
    # 150 dpi JPEGs keep repository size manageable while remaining print-legible.
    run("pdftoppm", "-jpeg", "-r", "150", "-jpegopt", "quality=92", str(source_pdf), str(pages / "page"))
    title = latex_title(source_tex, fallback)
    images = sorted(pages.glob("page-*.jpg"))
    lines = [
        '// Generated by typst/build_typst_papers.py.',
        '// Canonical scholarly source: ../' + source_pdf.name,
        '#set page(width: 8.5in, height: 11in, margin: 0pt)',
        '#set document(title: "' + typst_escape(title) + '")',
        '#set text(font: "Libertinus Serif")',
        '',
    ]
    for i, image in enumerate(images):
        if i:
            lines.append('#pagebreak()')
        lines.append(f'#image("pages/{image.name}", width: 100%, height: 100%, fit: "contain")')
    (out / "main.typ").write_text("\n".join(lines) + "\n")
    run("typst", "compile", "--root", str(out), str(out / "main.typ"), str(out / f"{stem}.pdf"))
    return out / f"{stem}.pdf", len(images)


if __name__ == "__main__":
    for dirname, stem, fallback in PAPERS:
        pdf, pages = build_one(dirname, stem, fallback)
        print(f"built {pdf.relative_to(ROOT)} ({pages} pages)")
